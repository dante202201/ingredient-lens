def migrate_legacy_additives() -> None:
    if not LEGACY.exists():
        return
    with open(LEGACY, encoding="utf-8") as f:
        raw = yaml.safe_load(f)
    ingredients = raw.get("ingredients") or {}
    for name, data in ingredients.items():
        data.setdefault("ingredient_type", "additive")
    out = {"default_type": "additive", "ingredients": ingredients}
    ING_DIR.mkdir(parents=True, exist_ok=True)
    with open(ING_DIR / "additives.yaml", "w", encoding="utf-8") as f:
        yaml.dump(out, f, allow_unicode=True, sort_keys=False)


